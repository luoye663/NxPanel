#!/bin/sh
set -eu
umask 077

binary=$(readlink -f "$1")
. /etc/os-release
case "$ID" in
    debian|rocky) VERSION_ID=${VERSION_ID%%.*} ;;
    alpine) VERSION_ID=$(printf '%s\n' "$VERSION_ID" | cut -d . -f 1,2) ;;
esac
case "$(uname -m)" in x86_64) arch=amd64 ;; aarch64) arch=arm64 ;; *) exit 1 ;; esac
runtime=$("$binary" -V 2>&1 | sed -n 's/^nginx version: //p')
digest() { sha256sum < "$1" | awk '{ print $1 }'; }
fingerprint=$(digest "$binary")
if [ "$2" = target ]; then
    printf '%s\t%s\t%s\t%s\t%s\n' "$ID:$VERSION_ID" "$arch" "${runtime%/*}" "${runtime#*/}" "$fingerprint"
    exit 0
fi

module=$2 symbol=$3 asset=/candidate/$4 install=/candidate/$5 uninstall=/candidate/$6
work=$(mktemp -d)
mkdir "$work/logs" "$work/conf.d"
master=
cleanup() {
    if [ -n "$master" ]; then kill -QUIT "$master" 2>/dev/null || true; wait "$master" || true; fi
}
trap cleanup EXIT
state=$work/state
asset_hash=$(digest "$asset")
destination=$state/$asset_hash/$module.so
fragment=$state/active/$module.conf
conf=$work/nginx.conf
cat > "$conf" <<EOF
worker_processes 1;
pid nginx.pid;
error_log stderr;
events {}
http {
    access_log off;
    include $work/http.inc;
    include $work/conf.d/*.conf;
    server {
        listen 127.0.0.1:18081;
        include $work/response.inc;
    }
}
EOF
: > "$work/http.inc"
printf 'return 200 before;\n' > "$work/response.inc"
set -- -p "$work/" -c "$conf" -g 'daemon off;'
"$binary" -e stderr "$@" &
master=$!
wait_for() {
    attempts=0
    until [ "$(wget -qO- -T 1 http://127.0.0.1:18081/)" = "$1" ]; do
        kill -0 "$master" && [ "$attempts" -lt 30 ] || return 1
        attempts=$((attempts + 1))
        sleep 0.2
    done
}
run_action() (
    action=$1 script=$2 payload=$3
    shift 3
    job=$(mktemp -d "$work/action.XXXXXX")
    cp "$script" "$job/action.sh"
    if [ "$action" = install ]; then cp "$payload" "$job/asset.so"; payload=$job/asset.so; fi
    cd "$job"
    exec env -i PATH=/usr/sbin:/usr/bin:/sbin:/bin LC_ALL=C LANG=C HOME="$job" TMPDIR="$job" \
        NXMODULE_PROTOCOL=1 NXMODULE_ACTION="$action" NXMODULE_ID="$module" NXMODULE_SYMBOL="$symbol" \
        NXMODULE_OS="$ID:$VERSION_ID" NXMODULE_ARCH="$arch" NXMODULE_RUNTIME="${runtime%/*}" \
        NXMODULE_ASSET="$payload" NXMODULE_ASSET_SHA256="$asset_hash" NXMODULE_DEST="$destination" \
        NXMODULE_WORK="$job" NXMODULE_STATE="$state" NXMODULE_FRAGMENT="$fragment" \
        NXMODULE_NGINX="$binary" NXMODULE_CONF="$conf" NXMODULE_CONF_ALIAS="$conf" NXMODULE_CONF_SHA256="$(digest "$conf")" \
        NXMODULE_BIN_SHA256="$fingerprint" NXMODULE_PANEL_DIR="$work" NXMODULE_MASTER_PID="$master" \
        NXMODULE_MASTER_START="$(sed 's/^.*) //' "/proc/$master/stat" | awk '{ print $20 }')" \
        /bin/sh "$job/action.sh" "$@"
)
wait_for before
before=$(cat "/proc/$master/task/$master/children")
run_action install "$install" "$asset" "$@"
test -n "$before"
test "$before" != "$(cat "/proc/$master/task/$master/children")"
test "$(digest "$destination")" = "$asset_hash"
grep -Fx "load_module \"$destination\";" "$fragment"
grep -F " $destination" "/proc/$master/maps" >/dev/null
if [ "$module" = geoip2 ]; then
    cat > "$work/http.inc" <<'EOF'
map $host $test_ip { default 81.2.69.142; }
geoip2 /test.mmdb { $test_country source=$test_ip country iso_code; }
EOF
    printf 'return 200 $test_country;\n' > "$work/response.inc"
    "$binary" -t "$@"
    kill -HUP "$master"
    wait_for GB
    status=0
    run_action uninstall "$uninstall" "$destination" "$@" || status=$?
    test "$status" -eq 10
    test -f "$fragment"
    wait_for GB
    : > "$work/http.inc"
    cat > "$work/conf.d/05-nxpanel-geoip2.conf" <<'EOF'
# Generated by nxPanel. Shared country lookup.
geoip2 "/test.mmdb" {
    $nxpanel_geoip_country_raw source=$remote_addr country iso_code;
    $nxpanel_geoip_registered_raw source=$remote_addr registered_country iso_code;
}
map $nxpanel_geoip_registered_raw $nxpanel_geoip_registered {
    ~^[A-Za-z][A-Za-z]$ $nxpanel_geoip_registered_raw;
    default ZZ;
}
map $nxpanel_geoip_country_raw $nxpanel_geoip_country {
    ~^[A-Za-z][A-Za-z]$ $nxpanel_geoip_country_raw;
    default $nxpanel_geoip_registered;
}
EOF
fi
printf 'return 200 after;\n' > "$work/response.inc"
"$binary" -t "$@"
run_action uninstall "$uninstall" "$destination" "$@"
test ! -e "$fragment"
if [ "$module" = geoip2 ]; then
    grep -Fx '# GeoIP2 is not loaded.' "$work/conf.d/05-nxpanel-geoip2.conf"
    test -s /test.mmdb
fi
"$binary" -t "$@"
wait_for after
