package georuntime

import (
	"fmt"
	"path/filepath"
	"strings"
)

const (
	CountryVariable     = "$nxpanel_geoip_country"
	SharedHeader        = "# Generated by nxPanel. Shared country lookup.\n"
	LegacyInclude       = "10-nxpanel-geo-access.conf"
	PolicyIncludePrefix = "20-nxpanel-access-policy-"
)

func ConfigPath(panelDir string) string {
	return filepath.Join(panelDir, "conf.d", "05-nxpanel-geoip2.conf")
}

func PolicyPath(panelDir, siteID string) string {
	return filepath.Join(panelDir, "conf.d", PolicyIncludePrefix+siteID+".conf")
}

func QuotePath(path string) (string, error) {
	if !filepath.IsAbs(path) || strings.ContainsAny(path, "$\x00\r\n") {
		return "", fmt.Errorf("GeoIP2 路径必须为安全的绝对路径")
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`).Replace(path) + `"`, nil
}

func Config(databasePath string) (string, error) {
	path, err := QuotePath(databasePath)
	if err != nil {
		return "", err
	}
	return SharedHeader + fmt.Sprintf(`geoip2 %s {
    $nxpanel_geoip_country_raw source=$remote_addr country iso_code;
    $nxpanel_geoip_registered_raw source=$remote_addr registered_country iso_code;
}
map $nxpanel_geoip_registered_raw $nxpanel_geoip_registered {
    ~^[A-Za-z][A-Za-z]$ $nxpanel_geoip_registered_raw;
    default ZZ;
}
map $nxpanel_geoip_country_raw %s {
    ~^[A-Za-z][A-Za-z]$ $nxpanel_geoip_country_raw;
    default $nxpanel_geoip_registered;
}
`, path, CountryVariable), nil
}
